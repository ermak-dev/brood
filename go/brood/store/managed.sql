CREATE TABLE managed_pools (
    uid TEXT PRIMARY KEY NOT NULL,
    name TEXT NOT NULL,
    connection TEXT NOT NULL,
    source TEXT NOT NULL,
    source_fingerprint TEXT NOT NULL,
    labels TEXT NOT NULL,
    max_actors INTEGER NOT NULL CHECK (max_actors >= 0),
    cpu_millicores INTEGER NOT NULL CHECK (cpu_millicores >= 0),
    memory_bytes INTEGER NOT NULL CHECK (memory_bytes >= 0),
    disk_bytes INTEGER NOT NULL CHECK (disk_bytes >= 0),
    template TEXT NOT NULL,
    state TEXT NOT NULL CHECK (state IN ('enabled', 'draining', 'deleted')),
    revision INTEGER NOT NULL CHECK (revision > 0),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE TABLE managed_actors (
    uid TEXT PRIMARY KEY NOT NULL,
    name TEXT NOT NULL,
    swarm_id TEXT NOT NULL,
    pool_uid TEXT NOT NULL REFERENCES managed_pools(uid),
    cluster_identity TEXT NOT NULL,
    source_fingerprint TEXT NOT NULL,
    template TEXT NOT NULL,
    incarnation INTEGER NOT NULL CHECK (incarnation > 0),
    phase TEXT NOT NULL CHECK (phase IN ('provisioning', 'running', 'stopping', 'stopped', 'error', 'deleting', 'deleted')),
    desired TEXT NOT NULL CHECK (desired IN ('running', 'stopped', 'deleted')),
    cpu_millicores INTEGER NOT NULL CHECK (cpu_millicores > 0),
    memory_bytes INTEGER NOT NULL CHECK (memory_bytes > 0),
    disk_bytes INTEGER NOT NULL CHECK (disk_bytes > 0),
    ctid INTEGER NOT NULL CHECK (ctid > 0),
    owner_nonce TEXT NOT NULL,
    operation_id TEXT NOT NULL,
    operation TEXT NOT NULL CHECK (operation IN ('create', 'start', 'stop', 'delete', 'reset')),
    upid TEXT NOT NULL,
    error TEXT NOT NULL,
    revision INTEGER NOT NULL CHECK (revision > 0),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    deleted_at TEXT,
    stage TEXT NOT NULL DEFAULT 'reconcile' CHECK (stage IN ('reconcile', 'create', 'start', 'stop', 'delete', 'done')),
    role TEXT NOT NULL DEFAULT 'worker' CHECK (role IN ('worker', 'master')),
    delegator_id TEXT NOT NULL DEFAULT '',
    parent_uid TEXT NOT NULL DEFAULT '',
    origin TEXT NOT NULL DEFAULT ''
);
CREATE TABLE managed_connections (
    uid TEXT PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    endpoint TEXT NOT NULL,
    token_id TEXT NOT NULL,
    token_secret TEXT NOT NULL,
    ca_pem TEXT NOT NULL,
    node TEXT NOT NULL,
    resource_pool TEXT NOT NULL,
    storage TEXT NOT NULL,
    network TEXT NOT NULL,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    runtime_config TEXT NOT NULL DEFAULT ''
)
